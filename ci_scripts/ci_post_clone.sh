#!/bin/sh
set -eu

expected_signing_team_id="QS3GC3CT43"
expected_cloud_team_id="1f3fb703-e0b0-42fc-bc0b-d00a3bfdf58e"

# Apple invokes this script from ci_scripts, not from the repository root.
script_dir="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
repository_dir="${CI_PRIMARY_REPOSITORY_PATH:-$(dirname "$script_dir")}"
cd "$repository_dir"

if [ "${CI_XCODE_CLOUD:-}" = "TRUE" ]; then
  # This account's Cloud runtime reports its account UUID. The legacy Developer
  # Team ID is also accepted, but the UUID must never become a signing Team ID.
  cloud_team_id="${CI_TEAM_ID:-}"
  case "$cloud_team_id" in
    "$expected_signing_team_id"|"$expected_cloud_team_id") ;;
    *)
      echo "Xcode Cloud Team ID $cloud_team_id is unrecognized; expected $expected_cloud_team_id or $expected_signing_team_id." >&2
      exit 65
      ;;
  esac

  # Cloud discovers a continuously present, checked-in project. Generate it locally;
  # never rewrite it here or resolve a different set of dependencies during an archive.
  project_dir="A Playa Named Gus.xcodeproj"
  if [ ! -f "$project_dir/project.pbxproj" ] || \
     [ ! -f "$project_dir/project.xcworkspace/xcshareddata/swiftpm/Package.resolved" ]; then
    echo "The checked-in Xcode project and Package.resolved are required for Xcode Cloud." >&2
    exit 66
  fi
  cat > Config/Local.xcconfig <<EOF
// Generated by ci_scripts/ci_post_clone.sh in Xcode Cloud.
DEVELOPMENT_TEAM = $expected_signing_team_id
CODE_SIGN_STYLE = Automatic
CODE_SIGN_IDENTITY =
CODE_SIGNING_REQUIRED = YES
CODE_SIGNING_ALLOWED = YES
GUS_WATCH_DEBUG_DYLIB = NO
EOF
  exit 0
fi

# Outside Cloud, retain the developer convenience of generating from project.yml.
if ! command -v xcodegen >/dev/null 2>&1; then
  if command -v brew >/dev/null 2>&1; then
    brew install xcodegen
  else
    echo "xcodegen is required to generate A Playa Named Gus.xcodeproj" >&2
    exit 69
  fi
fi

xcodegen generate
